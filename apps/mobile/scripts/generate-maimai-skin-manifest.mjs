import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
const root = path.resolve(import.meta.dirname, '..');
const items = JSON.parse(await fs.readFile(path.join(root, 'build/maimai-skin-audit/manifest.json'), 'utf8'));
const answer = JSON.parse(await fs.readFile(path.join(root, 'build/maimai-skin-audit/answer.json'), 'utf8'));
const revision = createHash('sha256').update(items.map(i => i.sha256).join('')).digest('hex').slice(0, 16);
const base = 'https://rranker-maimai-data.cn-nb1.rains3.com/chart-preview';
const text = `/** Generated by audit-maimai-skin.mjs and generate-maimai-skin-manifest.mjs. */
export const MAIMAI_CHART_PREVIEW_ASSET_BASE = '${base}' as const;
export const MAIMAI_CHART_PREVIEW_SKIN_REVISION = '${revision}' as const;
export type MaimaiChartPreviewSkinAsset = { readonly path: string; readonly url: string; readonly bytes: number; readonly width: number; readonly height: number; readonly sha256: string; readonly alphaBounds: readonly number[] };
export const MAIMAI_CHART_PREVIEW_ANSWER_SOUND = ${JSON.stringify({ ...answer, url: base + '/answer.wav' })} as const;
export const MAIMAI_CHART_PREVIEW_SKIN_ASSETS: readonly MaimaiChartPreviewSkinAsset[] = [
${items.map(i => '  ' + JSON.stringify({ ...i, url: base + '/' + i.path })).join(',\n')}
];
`;
await fs.writeFile(path.join(root, 'src/features/maimai-chart-preview/maimai-chart-preview-skin-manifest.generated.ts'), text);
console.log(revision);
